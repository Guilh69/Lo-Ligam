const perClau = new Map(ETIQUETAS.map(([c, oc, fr]) => [c, { oc, fr }]));

export function etiqueta(clau, fr = false) {
	const e = perClau.get(clau) ?? PER_FIN.find(([re]) => re.test(clau))?.slice(1);
	if (!e) return clau;
	const [oc, f] = Array.isArray(e) ? e : [e.oc, e.fr];
	return fr ? f : oc;
}

